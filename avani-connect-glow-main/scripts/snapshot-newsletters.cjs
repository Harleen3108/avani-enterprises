#!/usr/bin/env node
/**
 * snapshot-newsletters.cjs — bake the indexable newsletters into the build.
 *
 * Newsletters are fetched by the browser, so a crawler arriving at
 * /newsletters/<slug> got the generic shell: 57 words under an <h1> of
 * "Avani Enterprises", identical on every one. Allowing them into the index
 * without this would have published four more duplicates of the same page.
 *
 * Only the slugs in NEWSLETTER_INDEXABLE are snapshotted — the rest stay
 * noindexed and there is no reason to ship their bodies to the renderer.
 *
 * Mirrors scripts/snapshot-blog.cjs, including its failure behaviour: a
 * backend that is down at build time keeps the previous snapshot rather than
 * blanking the pages.
 */

const fs = require("fs");
const path = require("path");

const BACKEND_URL = process.env.BACKEND_URL || "https://avani-enterprises.onrender.com";
const OUT = path.join(__dirname, "..", "seo-lib", "newsletterContent.js");

/** The allowlist is the single source of truth for what may be indexed. */
function indexableSlugs() {
  const src = fs.readFileSync(path.join(__dirname, "..", "src", "data", "noindexPages.js"), "utf8");
  const m = src.match(/const NEWSLETTER_INDEXABLE = \[([\s\S]*?)\];/);
  if (!m) return [];
  return [...m[1].matchAll(/['"]([^'"]+)['"]/g)].map((x) => x[1]);
}

function write(obj, note) {
  const body =
    "// AUTO-GENERATED by scripts/snapshot-newsletters.cjs — do not edit.\n" +
    `// ${note}\n\n` +
    `export const newsletterContent = ${JSON.stringify(obj)};\n`;
  fs.writeFileSync(OUT, body, "utf8");
}

function previousCount() {
  try {
    const m = fs.readFileSync(OUT, "utf8").match(/export const newsletterContent = ([\s\S]*);\s*$/);
    return Object.keys(JSON.parse(m[1])).length;
  } catch {
    return null;
  }
}

(async () => {
  const allow = new Set(indexableSlugs());
  if (!allow.size) {
    write({}, "No newsletters are allowlisted for indexing.");
    console.log("ℹ️ No indexable newsletters — nothing to snapshot.");
    return;
  }

  try {
    const res = await fetch(`${BACKEND_URL}/api/newsletters`, { signal: AbortSignal.timeout(20000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const json = await res.json();
    const all = json.data || json || [];

    const trimmed = {};
    all.forEach((n) => {
      if (!n || !n.slug || !allow.has(n.slug)) return;
      if (n.isPublished === false) return;
      trimmed[n.slug] = {
        title: n.title || "",
        content: n.content || "",
        imageUrl: n.imageUrl || "",
        publishedAt: n.publishedAt || n.createdAt || "",
        updatedAt: n.updatedAt || n.publishedAt || n.createdAt || "",
      };
    });

    const missing = [...allow].filter((s) => !trimmed[s]);
    if (missing.length) {
      console.warn(
        `⚠️ Allowlisted but not found on the backend (still slugged the old way?): ${missing.join(", ")}`
      );
    }

    write(trimmed, `Snapshot of ${Object.keys(trimmed).length} indexable newsletter(s) from ${BACKEND_URL}`);
    console.log(`✅ seo-lib/newsletterContent.js — ${Object.keys(trimmed).length} newsletter(s) snapshotted`);
  } catch (err) {
    const prev = previousCount();
    if (prev !== null) {
      console.warn(`⚠️ Newsletter snapshot failed (${err.message}). Keeping previous snapshot of ${prev}.`);
    } else {
      write({}, `Backend unreachable at build time (${err.message}).`);
      console.warn(`⚠️ Newsletter snapshot failed (${err.message}). Wrote an empty one.`);
    }
  }
})();
